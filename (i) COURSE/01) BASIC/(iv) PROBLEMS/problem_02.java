// Caculating percentage of 5 subjects

public class problem_02 {
    public static void main(String[] args) {
        double bengali = 80;
        double english = 75;
        double math = 86;
        double physic = 76;
        double chemistry = 89;

        double percentage_subject = (bengali + english + math + physic + chemistry)/5;
        
        System.out.println("Percentage of subjects= " + percentage_subject);
    }
}
