// Program to print the multiplication table of 19
package QUESTIONS;

public class problem_05 {
    public static void main(String[] args) {
        
        int num = 19;
        int i = 1;
        while(i <= 10){
            System.out.println(num + " x " + i + " = " + (num * i));
            i++;
        }
    }
}
